namespace Oheangbu.Core.Domain
{
    // 인식기가 다루는 자모 9종 — 자음 5(ㄱㄴㅁㅅㅇ) + 모음 4(ㅏㅓㅗㅜ).
    // 어휘 공간 120자 고정·인식 클래스 9종 영구 고정(SPELL-VOCAB LOCKED)의 코드 표현이므로
    // 여기에 값을 추가하는 것은 개헌 사항이다 — 임의 확장 금지.
    public enum Jamo
    {
        // 자음(초성·종성 겸용) — 아음·설음·순음·치음·후음 순
        Giyeok, // ㄱ (목)
        Nieun,  // ㄴ (화)
        Mieum,  // ㅁ (토)
        Siot,   // ㅅ (금)
        Ieung,  // ㅇ (수)

        // 모음(중성) — 음양 × 단일/광역 프레임
        A,      // ㅏ (양·단일)
        Eo,     // ㅓ (음·단일)
        O,      // ㅗ (양·광역)
        U       // ㅜ (음·광역)
    }
}
