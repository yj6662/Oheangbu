        // ------------------------------------------------------------------ lookup (not a singleton: a cached asset reference)
        static MapStyle304SO cached, fallback;
        static bool looked;
        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
        static void ResetStatics() { cached = null; fallback = null; looked = false; }

        /// <summary>The asset at Resources/UI304/map/MapStyle304, else an in-memory instance with the code defaults
        /// (no sprites: callers fall back to UIIcons pictures and foundation sprites).</summary>
        public static MapStyle304SO Resolve()
        {
            if (cached != null) return cached;
            if (!looked) { looked = true; cached = Resources.Load<MapStyle304SO>(ResourcePath); if (cached != null) return cached; }
            if (fallback == null)
            {
                fallback = CreateInstance<MapStyle304SO>();
                fallback.name = "MapStyle304 (code defaults)"; fallback.hideFlags = HideFlags.DontSave;
            }
            return fallback;
        }

        public static bool IsFallback(MapStyle304SO style) => style == null || style == fallback;

        /// <summary>D13 pictogram for an IMapMarkerSource304 entry (the HUD bearing line's 32 px place marks): Rest = roof,
        /// Place = arch, Coin = 조선통보. Pin and Objective return null (the bearing line draws its X / 목적 방점).</summary>
        public Sprite Pictogram(MapMarkerKind304 kind)
        {
            switch (kind)
            {
                case MapMarkerKind304.Rest: return PictRest;
                case MapMarkerKind304.Place: return PictCave;
                case MapMarkerKind304.Coin: return Coin;
                default: return null;
            }
        }

        /// <summary>D13 pictogram for a marker kind (30~32 px). null when the asset is missing.</summary>
        public Sprite Pictogram(WorldMapMarkerKind kind)
        {
            switch (kind)
            {
                case WorldMapMarkerKind.Rest: case WorldMapMarkerKind.Checkpoint: return PictRest;
                case WorldMapMarkerKind.Mountain: return PictMountain;
                case WorldMapMarkerKind.Gate: return PictGate != null ? PictGate : PictCave;
                case WorldMapMarkerKind.Settlement: return PictVillage != null ? PictVillage : PictRest;
                case WorldMapMarkerKind.Drop: return Coin;
                default: return PictCave;
            }
        }
